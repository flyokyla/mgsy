g=1;
s=16;
c=(s+g)/25;
l=1;
y0=0;
yl=0;
n=9;
A=zeros(n,n);
A(1,1)=1.;
A(n,n)=1.;
b=zeros(n,1);
b(1)=y0;
b(n)=yl;
h=l/(n-1);

for i=2:n-1
   A(i,i-1)=1.;
   A(i,i+1)=1.;
   x=h*(i-1);
   p= s./(l^2+4*x.*(l-x));
   f=-c*(2-p.*x.*(l-x));
   A(i,i)=-2+h^2*p;
   b(i)=h^2*f;
end;

y=A\b;

disp('матрица системы разностных уравнений')
disp(A)

disp('вектор правой части системы разностных уравнений')
disp(b)

disp('решение y:')
disp(y)

x = 0:0.125:1;
y = (-1) * y;
plot(x, y)

